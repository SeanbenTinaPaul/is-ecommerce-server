"""
Phase 3: Intelligent Index Selection
======================================
วัตถุประสงค์: เลือก indexes ที่ดีที่สุดจาก Phase 2 benchmark
โดยใช้ Weighted Scoring พร้อม Write Penalty

Usage (run from server/ directory):
  python research_experiment/scripts/phase3_selector.py

Scoring Formula:
  Final_Score = (Freq_Score * Improvement_Pct) / (Penalty ^ 1.5)

Write Penalty:
  - Cart, Order, ProductOnOrder, Payment = 2.5 (Critical write path Flash Sale)
  - Product = 1.2 (Mostly read, stock updates)
  - Others = 1.0

Scenario Tags:
  - Dynamic_FlashSale: Order, Cart, ProductOnOrder, Discount, or id contains 'FlashSale'
  - Base_Standard: Everything else

Outputs:
  - results/phase3_final_ranking.csv
  - artifacts/final_indexes.sql
  - artifacts/optimization_chart.png

Dependencies:
  pip install matplotlib pandas
"""

import json
import csv
import sys
from pathlib import Path

script_dir = Path(__file__).resolve().parent
project_dir = script_dir.parent
results_dir = project_dir / 'results'
artifacts_dir = project_dir / 'artifacts'

# สร้าง directories ถ้ายังไม่มี
results_dir.mkdir(parents=True, exist_ok=True)
artifacts_dir.mkdir(parents=True, exist_ok=True)


# =============================================================================
# Configuration
# =============================================================================
TOP_N = 15   # เลือก Top 15 Candidates

# Write Penalty Mapping
WRITE_PENALTIES = {
    'Cart': 2.5,
    'ProductOnCart': 2.5,
    'Order': 2.5,
    'ProductOnOrder': 2.5,
    'Payment': 2.5,
    'Product': 1.2,
}
DEFAULT_PENALTY = 1.0

# Dynamic Flash Sale Tables
DYNAMIC_TABLES = {'Order', 'Cart', 'ProductOnOrder', 'Discount'}


# =============================================================================
# Scoring Functions
# =============================================================================
def get_write_penalty(table_name):
    """คืนค่า Write Penalty ตาม table"""
    return WRITE_PENALTIES.get(table_name, DEFAULT_PENALTY)


def get_scenario_tag(candidate):
    """กำหนด Scenario Tag: Dynamic_FlashSale หรือ Base_Standard"""
    table = candidate.get('table', '')
    cid = candidate.get('id', '')

    if table in DYNAMIC_TABLES or 'FlashSale' in cid or 'flashsale' in cid.lower():
        return 'Dynamic_FlashSale'
    return 'Base_Standard'


def calculate_score(freq_score, improvement_pct, penalty):
    """
    Final_Score = (Freq_Score * Improvement_Pct) / (Penalty ^ 1.5)
    Punish write-heavy tables exponentially to avoid deadlocks
    """
    if penalty <= 0:
        penalty = 1.0
    return (freq_score * improvement_pct) / (penalty ** 1.5)


# =============================================================================
# Output: CSV Report
# =============================================================================
def write_csv(ranked, output_path):
    """สร้าง CSV report"""
    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        writer.writerow(['Rank', 'ID', 'Table', 'Tag', 'Imp_Pct', 'Freq', 'Penalty', 'Score'])

        for i, c in enumerate(ranked, 1):
            writer.writerow([
                i,
                c['id'],
                c['table'],
                c['tag'],
                round(c['improvement_pct'], 2),
                c['freq_score'],
                c['penalty'],
                round(c['score'], 2)
            ])

    print(f"📄 CSV saved: {output_path}")


# =============================================================================
# Output: SQL File
# =============================================================================
def write_sql(ranked, output_path):
    """สร้าง SQL file พร้อม CREATE INDEX statements"""
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write("-- ============================================================\n")
        f.write("-- Phase 3: Final Selected Indexes\n")
        f.write("-- ============================================================\n")
        f.write("-- Auto-generated by phase3_selector.py\n")
        f.write(f"-- Total Selected: {len(ranked)} indexes\n")
        f.write("-- Scoring: Final_Score = (Freq * Imp%) / (Penalty ^ 1.5)\n")
        f.write("-- ============================================================\n\n")

        for i, c in enumerate(ranked, 1):
            tag = c['tag']
            score = round(c['score'], 1)
            imp = round(c['improvement_pct'], 1)
            table = c['table']
            idx_def = c['index_def']

            f.write(f"-- [{tag}] Rank #{i} | Score: {score} | Imp: {imp}% | Table: {table}\n")

            # แปลง index_def ให้มีชื่อ index
            # เช่น CREATE INDEX ON "X" ("col") → CREATE INDEX IF NOT EXISTS "idx_..." ON "X" ("col")
            idx_name = f"idx_p3_{c['id'].lower()}"
            named_def = idx_def.replace(
                'CREATE INDEX ON',
                f'CREATE INDEX IF NOT EXISTS "{idx_name}" ON'
            )
            f.write(f"{named_def};\n\n")

        # ANALYZE statements
        tables_used = sorted(set(c['table'] for c in ranked))
        f.write("-- Update Statistics\n")
        for t in tables_used:
            f.write(f'ANALYZE "{t}";\n')

    print(f"📄 SQL saved: {output_path}")


# =============================================================================
# Output: Visualization
# =============================================================================
def create_chart(ranked, output_path, top_n=10):
    """สร้าง horizontal bar chart ของ Top N indexes"""
    try:
        import matplotlib
        matplotlib.use('Agg')  # Non-interactive backend
        import matplotlib.pyplot as plt
    except ImportError:
        print("⚠️ matplotlib not installed. Skipping chart.")
        print("   Install: pip install matplotlib")
        return

    # เตรียมข้อมูล Top N
    top = ranked[:top_n]
    top.reverse()  # reverse เพื่อให้ rank 1 อยู่บนสุด

    labels = [c['id'] for c in top]
    values = [c['improvement_pct'] for c in top]
    colors = ['#E74C3C' if c['tag'] == 'Dynamic_FlashSale' else '#3498DB' for c in top]

    # สร้าง chart
    fig, ax = plt.subplots(figsize=(12, 7))

    bars = ax.barh(labels, values, color=colors, edgecolor='white', linewidth=0.5, height=0.6)

    # เพิ่ม value labels
    for bar, val in zip(bars, values):
        ax.text(bar.get_width() + 0.5, bar.get_y() + bar.get_height() / 2,
                f'{val:.1f}%', va='center', fontsize=9, fontweight='bold')

    # Styling
    ax.set_xlabel('Improvement %', fontsize=12, fontweight='bold')
    ax.set_title(f'Phase 3: Top {top_n} Index Candidates by Improvement %',
                 fontsize=14, fontweight='bold', pad=15)
    ax.set_xlim(0, max(values) * 1.15)

    # Grid
    ax.xaxis.grid(True, alpha=0.3, linestyle='--')
    ax.set_axisbelow(True)

    # Legend
    from matplotlib.patches import Patch
    legend_elements = [
        Patch(facecolor='#3498DB', label='Base_Standard'),
        Patch(facecolor='#E74C3C', label='Dynamic_FlashSale'),
    ]
    ax.legend(handles=legend_elements, loc='lower right', fontsize=10)

    # Score annotations on bars
    for bar, c in zip(bars, top):
        score_text = f'Score: {c["score"]:.0f}'
        x_pos = min(bar.get_width() * 0.5, max(values) * 0.4)
        ax.text(x_pos, bar.get_y() + bar.get_height() / 2,
                score_text, va='center', ha='center',
                fontsize=7, color='white', fontweight='bold')

    plt.tight_layout()
    plt.savefig(output_path, dpi=150, bbox_inches='tight')
    plt.close()

    print(f"📊 Chart saved: {output_path}")


# =============================================================================
# Main
# =============================================================================
def main():
    print("=" * 60)
    print("🧠 PHASE 3: INTELLIGENT INDEX SELECTION")
    print("=" * 60)

    # 1. Load data
    input_path = results_dir / 'phase2_results_filtered.json'
    if not input_path.exists():
        print(f"❌ Input not found: {input_path}")
        sys.exit(1)

    with open(input_path, 'r', encoding='utf-8') as f:
        candidates = json.load(f)

    print(f"\n📦 Loaded {len(candidates)} candidates from Phase 2")

    # 2. Score and tag each candidate
    scored = []
    for c in candidates:
        table = c.get('table', '')
        freq = c.get('freq_score', 0)
        imp = c.get('improvement_pct', 0)

        penalty = get_write_penalty(table)
        tag = get_scenario_tag(c)
        score = calculate_score(freq, imp, penalty)

        scored.append({
            **c,
            'penalty': penalty,
            'tag': tag,
            'score': score,
        })

    # 3. Sort by Final_Score descending
    scored.sort(key=lambda x: x['score'], reverse=True)

    # 4. Select Top N
    selected = scored[:TOP_N]

    # 5. Print Top 5 to terminal
    print(f"\n🏆 Top 5 Selected Indexes:")
    print("-" * 80)
    print(f"{'Rank':<5} {'ID':<35} {'Tag':<20} {'Imp%':<8} {'Score':<8}")
    print("-" * 80)
    for i, c in enumerate(selected[:5], 1):
        print(f"{i:<5} {c['id']:<35} {c['tag']:<20} {c['improvement_pct']:<8.1f} {c['score']:<8.1f}")
    print("-" * 80)

    # 6. Tag distribution summary
    base_count = sum(1 for c in selected if c['tag'] == 'Base_Standard')
    dynamic_count = sum(1 for c in selected if c['tag'] == 'Dynamic_FlashSale')
    print(f"\n📊 Tag Distribution (Top {TOP_N}):")
    print(f"   Base_Standard:     {base_count}")
    print(f"   Dynamic_FlashSale: {dynamic_count}")

    # 7. Outputs
    print("\n📁 Generating outputs...\n")

    # CSV
    csv_path = results_dir / 'phase3_final_ranking.csv'
    write_csv(selected, csv_path)

    # SQL
    sql_path = artifacts_dir / 'final_indexes.sql'
    write_sql(selected, sql_path)

    # Chart
    chart_path = artifacts_dir / 'optimization_chart.png'
    create_chart(selected, chart_path, top_n=10)

    # Done
    print("\n" + "=" * 60)
    print("✅ PHASE 3 COMPLETE!")
    print("=" * 60)
    print(f"   Selected:  {len(selected)} / {len(candidates)} candidates")
    print(f"   CSV:       {csv_path}")
    print(f"   SQL:       {sql_path}")
    print(f"   Chart:     {chart_path}")


if __name__ == '__main__':
    main()
